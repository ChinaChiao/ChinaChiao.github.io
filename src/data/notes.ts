export function getNote(slug: string) {
  return notes.find((item) => item.slug === slug)
}

export function featuredNotes() {
  const pinned = notes.find((item) => item.pinned) ?? notes[0]
  const latest = notes
    .filter((item) => item.slug !== pinned.slug)
    .slice()
    .sort((a, b) => (a.date < b.date ? 1 : -1))
    .slice(0, 2)
  return { pinned, latest }
}

export function notesByDate() {
  return notes.slice().sort((a, b) => (a.date < b.date ? 1 : -1))
}

export function formatDate(iso: string) {
  const [y, m, d] = iso.split('-')
  return `${y}.${m}.${d}`
}
